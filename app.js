function read(type) {
  // Published Planity data must take precedence over old browser-only edits.
  if (type === "services") return structuredClone(defaults.services);
  const saved = localStorage.getItem(keys[type]);
  if (!saved) return structuredClone(defaults[type]);

  try {
    const parsed = JSON.parse(saved);
    if (type === "products" && Array.isArray(parsed) && parsed.some((product) => !product.image && !product.images)) {
      return structuredClone(defaults[type]);
    }
    return Array.isArray(parsed) ? parsed : structuredClone(defaults[type]);
  } catch {
    return structuredClone(defaults[type]);
  }
}

function write(type) {
  localStorage.setItem(keys[type], JSON.stringify(state[type]));
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function getCategoryMeta(category) {
  return planityCategoryMeta[category] || {
    shortTitle: category,
    description: ""
  };
}

function normalizeSearch(value) {
  return String(value || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

function getServiceSearchText(service) {
  const meta = getCategoryMeta(service.category);
  return normalizeSearch([
    service.name,
    service.category,
    meta.shortTitle,
    service.description,
    service.duration,
    service.price
  ].join(" "));
}

function getServiceSearchScore(service, queryTokens) {
  if (!queryTokens.length) return 1;

  const name = normalizeSearch(service.name);
  const category = normalizeSearch(`${service.category} ${service.categoryShortTitle || ""}`);
  const haystack = getServiceSearchText(service);
  const words = haystack.split(/\s+/).filter(Boolean);
  let score = 0;

  for (const token of queryTokens) {
    if (name.startsWith(token)) {
      score += 100;
      continue;
    }

    if (words.some((word) => word.startsWith(token))) {
      score += 70;
      continue;
    }

    if (name.includes(token)) {
      score += 45;
      continue;
    }

    if (category.includes(token)) {
      score += 30;
      continue;
    }

    if (haystack.includes(token)) {
      score += 15;
      continue;
    }

    return 0;
  }

  return score;
}

